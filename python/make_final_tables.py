"""
python/make_final_tables.py

Builds results/final_tables.md (the single source of truth for all reported numbers)
directly from the raw run logs, so no number is ever copied by hand:
  - results/task8_final_output.txt     main study      (python/run_task8.py configs/models.toml ...)
  - results/lownoise/task8_output.txt  noise check     (python/run_task8.py configs/models_lownoise.toml ...)
  - data/features_meta_v2.json         feature counts

Every table keeps the exact title printed by run_task8.py as its '### ' heading, which is
how python/check_tables.py matches each markdown table back to its raw source.

Usage:  python python/make_final_tables.py
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from table_utils import parse_text_tables, cell_by_header, first_number

MAIN_LOG = "results/task8_final_output.txt"
LOWNOISE_LOG = "results/lownoise/task8_output.txt"
META = "data/features_meta_v2.json"
OUT = "results/final_tables.md"
README = "README.md"
LOWNOISE_PREFIX = "Low-Noise Sensitivity: "


def md_table(tab, bold_first=True):
    lines = ["| " + " | ".join(tab["header"]) + " |", "|" + "---|" * len(tab["header"])]
    for r in tab["rows"]:
        cells = [f"**{r[0]}**" if bold_first else r[0]] + r[1:]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def find(tables, pattern):
    """Title of the single table whose title matches the regex pattern."""
    hits = [t for t in tables if re.search(pattern, t)]
    if len(hits) != 1:
        raise KeyError(f"expected exactly one table matching '{pattern}', found {hits}")
    return hits[0]


def main():
    raw = open(MAIN_LOG, encoding="utf-8").read()
    T = parse_text_tables(raw)
    ln_raw = open(LOWNOISE_LOG, encoding="utf-8").read() if os.path.exists(LOWNOISE_LOG) else None
    LN = parse_text_tables(ln_raw) if ln_raw else {}

    t_thr = find(T, r"^Validation Normal Thresholds")
    t1 = find(T, r"^TABLE 1:")
    t1_pt = find(T, r"^Table 1 Per Attack Type")
    t1_cm = find(T, r"^Table 1 Classification Metrics")
    t2 = find(T, r"^TABLE 2:")
    t2_pt = find(T, r"^Table 2 Held-Out")
    t2_cm = find(T, r"^Table 2 Classification Metrics")
    t_sig = find(T, r"^\(1\)")
    t_abl = find(T, r"^\(2\)")
    t_lm = find(T, r"^\(3\)")
    t_proxy = find(T, r"^\(4\)")
    t_mim_val = find(T, r"^\(5\) MIMIC ATTACK BENCHMARK: val_donors")
    t_mim_tr = find(T, r"^\(5\) MIMIC ATTACK BENCHMARK: train_donors")
    t_mim_bins = find(T, r"^\(6\)")

    def v(title, row, col, tables=T):
        return first_number(cell_by_header(tables[title], row, col))

    # ------------------------------------------------------------------
    # Headline numbers (looked up from the parsed tables, never typed in)
    # ------------------------------------------------------------------
    RF, AE, AE12, MH, CHI, LNR = ("RF w/o D3 (Primary)", "Autoencoder (All: A-D2)", "Autoencoder (D1+D2)",
                                  "Mahalanobis (Ledoit-Wolf)", "Chi-Square", "Calibrated LNR")
    ex = {m: v(t1, m, "Exact @ 5% FA") for m in [RF, AE, AE12, MH, CHI, LNR]}
    mim = {m: v(t_mim_val, m, "Det @ 5% FA") for m in [RF, AE, AE12, MH, CHI, LNR]}
    mim_auc = {m: v(t_mim_val, m, "Mimic AUC [95% CI]") for m in [RF, AE, AE12, MH, CHI, LNR]}
    rf_t2 = "RF (Seen Only -> Held-Out)"
    rf_unseen_exact = v(t2, rf_t2, "Exact @ 5% FA")
    proxy = T[t_proxy]
    r2 = {r[0]: float(r[2]) for r in proxy["rows"]}
    exact_auc_blk = {r[0]: float(r[5]) for r in proxy["rows"]}
    null_rf = re.search(r"RF Primary Permutation Null Check:\s*(.*)", raw).group(1).strip()
    null_ae = re.search(r"AE All Permutation Null Check:\s*(.*)", raw).group(1).strip()
    rf_params = re.search(r"Chosen Hyperparameters \(Validation Best\): (.*)", raw).group(1).strip()

    meta = json.load(open(META))["feature_groups"]
    counts = {k: meta[k]["count"] for k in meta}

    out = []
    w = out.append
    w("# Final Benchmarking Tables & Experimental Results")
    w("")
    w("**Single source of truth.** This file is generated by `python/make_final_tables.py` from the raw run logs "
      f"`{MAIN_LOG}` (main study) and `{LOWNOISE_LOG}` (low-noise sensitivity check), and verified cell-by-cell by "
      "`python/check_tables.py` (report: `results/check_tables_report.txt`). Do not edit numbers by hand: re-run the "
      "pipeline and regenerate. All detection rates use thresholds set at the 95th (5% FA) or 99th (1% FA) percentile "
      "of each detector's scores on validation normal rows; realized false-alarm rates on test normal rows are reported "
      "alongside. Confidence intervals are 95% group-bootstrap intervals (1,000 resamples of operating-point groups).")
    w("")
    w("---")
    w("")
    headline = []
    h = headline.append
    h(f"1. **Classical BDD cannot see exact AC stealth attacks.** At the 5% validation false-alarm threshold the "
      f"chi-square test detects {ex[CHI]:.2f}% and the calibrated largest normalised residual {ex[LNR]:.2f}% of exact AC "
      "attacks, i.e. chance level, as theory predicts (residuals are unchanged by a = h(x+c) - h(x)).")
    h(f"2. **Data-driven detectors catch the project's exact AC attacks** (Random Forest {ex[RF]:.2f}%, Autoencoder "
      f"{ex[AE]:.2f}%, per-hour Mahalanobis distance on the state estimate {ex[MH]:.2f}%), and the RF trained only on "
      f"random and linearised attacks still detects {rf_unseen_exact:.2f}% of held-out exact AC attacks (Table 2, "
      "leak-free split).")
    fa5 = {m: first_number(cell_by_header(T[t_mim_val], m, "Realized Normal FA")) for m in [RF, AE, AE12, MH, CHI, LNR]}
    DISPLAY = {RF: "primary Random Forest", AE: "Autoencoder (all features)", AE12: "Autoencoder (D1+D2)", MH: "Mahalanobis detector"}
    best_auc_m = max([RF, AE, AE12, MH], key=lambda m: mim_auc[m])
    shift_mim = float(re.search(r"median max voltage shift = ([0-9.]+) pu", raw).group(1))
    shift_ex = float(re.search(r"project exact AC attacks in test split: ([0-9.]+) pu", raw).group(1))
    h(f"3. **But they do so by recognising an atypical state, not a physics violation.** Against a distribution-aware "
      f"('mimic') exact AC attacker that moves the estimate onto a genuine normal state from another day at the same hour "
      f"(donors never seen in training), detection at the 5% threshold collapses to the false-alarm level for every "
      f"detector: RF {mim[RF]:.2f}% (false alarms {fa5[RF]:.2f}%), Autoencoder {mim[AE]:.2f}% ({fa5[AE]:.2f}%), "
      f"Mahalanobis {mim[MH]:.2f}% ({fa5[MH]:.2f}%), chi-square {mim[CHI]:.2f}% ({fa5[CHI]:.2f}%). The best ranking "
      f"score is the {DISPLAY[best_auc_m]}'s AUC of {mim_auc[best_auc_m]:.3f}, a weak signal with no practical "
      f"detection value. The mimic attacks are not smaller than the project's own exact AC attacks (median maximum voltage "
      f"shift {shift_mim:.4f} pu vs {shift_ex:.4f} pu; Section 4).")
    h(f"4. **The 'physics-informed' feature groups act as state proxies.** Group C (leverage) is predicted from the state "
      f"estimate alone with median R^2 = {r2['C: measurement leverage']:.4f}. In Group B the KCL power-balance mismatches "
      f"are dominated by meter noise (median R^2 = {r2['B: KCL power-balance mismatch']:.4f}) and separate exact AC "
      f"attacks only weakly (AUC {exact_auc_blk['B: KCL power-balance mismatch']:.3f}); Group B's discriminative power "
      f"comes from the neighbour-voltage block (exact AC AUC {exact_auc_blk['B: voltage vs neighbour mean']:.3f}), "
      "itself a function of the state (Section 5).")
    if LN:
        ln_t1 = find(LN, r"^TABLE 1:")
        ln_mim = find(LN, r"^\(5\) MIMIC ATTACK BENCHMARK: val_donors")
        ln_pt = find(LN, r"^Table 1 Per Attack Type")
        h(f"5. **Conclusions do not depend on the conservative meter noise.** With ~10x lower power-meter noise, "
          f"chi-square detection of linearised single-bus attacks rises from {v(t1_pt, CHI, 'lin_single'):.2f}% to "
          f"{v(ln_pt, CHI, 'lin_single', LN):.2f}%, yet exact AC attacks remain invisible to BDD "
          f"({v(ln_t1, CHI, 'Exact @ 5% FA', LN):.2f}%) and mimic attacks remain invisible to the RF "
          f"({v(ln_mim, RF, 'Det @ 5% FA', LN):.2f}%) and Autoencoder ({v(ln_mim, AE, 'Det @ 5% FA', LN):.2f}%) even though "
          f"the Autoencoder now detects {v(ln_t1, AE, 'Exact @ 5% FA', LN):.2f}% of the random-shift exact AC attacks. "
          f"The only residual signal comes from the D3 'change from previous hour' features, which assume a clean previous "
          f"sample: RF with D3 reaches mimic AUC {v(ln_mim, 'RF with D3 (Clean Prev)', 'Mimic AUC [95% CI]', LN):.3f} but detects "
          f"only {v(ln_mim, 'RF with D3 (Clean Prev)', 'Det @ 5% FA', LN):.2f}% at a "
          f"{v(ln_mim, 'RF with D3 (Clean Prev)', 'Realized Normal FA', LN):.2f}% false-alarm rate (Section 8).")
    w("## Headline Findings")
    w("")
    out.extend(headline)
    w("")
    w("---")
    w("")
    w("## 0. Feature Counts per Group (from `data/features_meta_v2.json`)")
    w("")
    w("| Feature Group | Count | Content |")
    w("|---|---|---|")
    w(f"| **A: Residuals** | {counts['group_a_residuals']} | raw and normalised residuals (163 + 163), objective J, max normalised residual |")
    w(f"| **B: Consistency** | {counts['group_b_consistency']} | KCL P/Q mismatches (66), voltage minus neighbour mean (33), measured minus recomputed branch flows (64) |")
    w(f"| **C: Sensitivity** | {counts['group_c_sensitivity']} | measurement leverage (hat-matrix diagonal) at the estimated state |")
    w(f"| **D1: Raw** | {counts['group_d1_raw']} | raw measurements z (163) and state estimate (65) |")
    w(f"| **D2: Hourly deviation** | {counts['group_d2_hourly_forecast']} | deviation from train-normal hour-of-day means |")
    w(f"| **D3: Change from previous** | {counts['group_d3_change_prev']} | change from previous hour's (assumed clean) normal sample |")
    prim = sum(counts[k] for k in ["group_a_residuals", "group_b_consistency", "group_c_sensitivity", "group_d1_raw", "group_d2_hourly_forecast"])
    w(f"| **Primary model (A+B+C+D1+D2)** | {prim} | used by the primary RF and the 'All' Autoencoder |")
    w("")
    w(f"Random Forest hyperparameters chosen on the validation split: `{rf_params}`.")
    w("")
    w("---")
    w("")
    w("## 1. Operating Thresholds (validation normal rows) and Realized Test False Alarms")
    w("")
    w(f"### {t_thr}")
    w("")
    w(md_table(T[t_thr]))
    w("")
    w("---")
    w("")
    w("## 2. Table 1: Standard Test Split")
    w("")
    w("Group-aware split (60/20/20 by operating point); 1,000 normal and 1,000 attacked test rows.")
    w("")
    for t in [t1, t1_pt, t1_cm]:
        w(f"### {t}")
        w("")
        if T[t]["note"]:
            w(f"*{T[t]['note'].strip('()')}.*")
            w("")
        w(md_table(T[t]))
        w("")
    w("---")
    w("")
    w("## 3. Table 2: Unseen-Attack Generalisation (leak-free)")
    w("")
    w("The RF is trained only on random and linearised attacks; exact AC and limited-meter attacks are never seen in "
      "training. Every row keeps its operating-point group's split, so a held-out attack is evaluated only if its group is "
      "in the test split (held-out attacks in train/val groups are dropped). The earlier version moved all held-out "
      "attacks into the test set, which left 2,026 of 2,511 of them with their normal twin in training (group leakage) and "
      "inflated N to 4,026; those superseded numbers are not used anywhere.")
    w("")
    for t in [t2, t2_pt, t2_cm]:
        w(f"### {t}")
        w("")
        if T[t]["note"]:
            w(f"*{T[t]['note'].strip('()')}.*")
            w("")
        w(md_table(T[t]))
        w("")
    w("---")
    w("")
    w("## 4. Distribution-Aware (Mimic) Exact AC Stealth Attacks")
    w("")
    w("Generated by `julia/09_mimic_attacks.jl` (config `configs/mimic_attacks_v2.toml`). For each of the 1,000 test "
      "operating points, the attacker picks a genuine normal operating point from a different day at the same hour (the "
      "donor) and injects the exact AC stealth attack with c = x_hat_donor - x_hat_target, so the re-estimated state is "
      "both residual-consistent and typical for that hour. The detectors, feature pipeline and thresholds are exactly "
      "those of Table 1 (run_task8.py re-scores the standard test rows and asserts the scores are identical before "
      "scoring the mimic rows). Primary set: donors from validation normals (states no detector was trained on); "
      "secondary set: donors from training normals.")
    w("")
    for t in [t_mim_val, t_mim_tr, t_mim_bins]:
        w(f"### {t}")
        w("")
        w(md_table(T[t]))
        w("")
    w("Figure: `results/mimic_vs_exact.png`.")
    w("")
    w("---")
    w("")
    w("## 5. State-Proxy Diagnostics: What Groups B and C Encode")
    w("")
    w("R2 columns: share of each feature column's variance on test normal rows explained by a quadratic ridge regression "
      "on the 65-element state estimate (fitted on train normals); median and minimum over the block's columns. "
      "Remaining columns: RF (Table 1 hyperparameters) trained on that block alone.")
    w("")
    w(f"### {t_proxy}")
    w("")
    w(md_table(T[t_proxy]))
    w("")
    w("---")
    w("")
    w("## 6. Detection vs Attack Size, Feature Ablation, Limited-Meter Attacks")
    w("")
    for t in [t_sig, t_abl, t_lm]:
        w(f"### {t}")
        w("")
        w(md_table(T[t]))
        w("")
    w("---")
    w("")
    w("## 7. Permutation Null Check (test labels permuted, 20 seeds)")
    w("")
    w(f"- RF Primary: {null_rf}")
    w(f"- Autoencoder (All): {null_ae}")
    w("")
    w("Both are centred on 0.5, i.e. no information leaks through the evaluation code itself.")
    w("")
    if LN:
        w("---")
        w("")
        w("## 8. Low-Noise Sensitivity Check")
        w("")
        w("Identical pipeline, seeds and operating points (configs `*_lownoise.toml`), with meter noise reduced from "
          "0.005/0.010/0.008 pu (voltage/injection/flow) to 0.001/0.001/0.0008 pu. In the main study the injection-meter "
          "standard deviation (100 kW) is comparable to a typical bus load (~120 kW), which weakens every residual-based "
          "test; this check shows which conclusions depend on that choice. Full log: "
          f"`{LOWNOISE_LOG}`; figures in `results/lownoise/`.")
        w("")
        for pat in [r"^Validation Normal Thresholds", r"^TABLE 1:", r"^Table 1 Per Attack Type", r"^Table 1 Classification Metrics",
                    r"^\(5\) MIMIC ATTACK BENCHMARK: val_donors"]:
            t = find(LN, pat)
            w(f"### {LOWNOISE_PREFIX}{t}")
            w("")
            w(md_table(LN[t]))
            w("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print(f"Wrote {OUT}")

    # Same headline block into README.md, between the generated-headline markers
    readme = open(README, encoding="utf-8").read()
    begin_tag = "<!-- BEGIN GENERATED HEADLINE (python/make_final_tables.py) -->"
    end_tag = "<!-- END GENERATED HEADLINE -->"
    i, j = readme.index(begin_tag) + len(begin_tag), readme.index(end_tag)
    readme = readme[:i] + "\n" + "\n".join(headline) + "\n" + readme[j:]
    with open(README, "w", encoding="utf-8") as f:
        f.write(readme)
    print(f"Updated headline block in {README}")


if __name__ == "__main__":
    main()
